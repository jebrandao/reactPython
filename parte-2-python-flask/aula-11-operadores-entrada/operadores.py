# Operadores aritméticos
print(5 + 2)  # 7   soma
print(5 - 2)  # 3   subtração
print(5 * 2)  # 10  multiplicação
print(9 / 3)  # 3.0 divisão (sempre devolve float)
print(10 // 3)  # 3   divisão inteira
print(10 % 3)  # 1   módulo: o resto da divisão

# Operadores de comparação (o resultado é sempre True ou False)
a, b = 7, 4
print(a == b)  # igualdade
print(a != b)  # diferença
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)

# Atenção: "=" atribui um valor; "==" compara dois valores.
