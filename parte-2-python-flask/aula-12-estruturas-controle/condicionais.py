nome = "Vanessa"

# Condicional simples
if nome == "Vanessa":
    print("Olá, Vanessa!")

# Condicional composta (if / else)
if nome == "Vanessa":
    print("Você é a Vanessa.")
else:
    print("Você não é a Vanessa.")

# Condicional encadeada (if / elif / else): vários caminhos
nota = 7.5
if nota >= 9:
    print("Excelente")
elif nota >= 7:
    print("Aprovado")
elif nota >= 5:
    print("Recuperação")
else:
    print("Reprovado")
